export function t(key: string, lang: Lang): string {
  const pair = S[key];
  if (!pair) return key;
  return lang === 'ar' ? pair[0] : pair[1];
}

export function relTime(ts: number, lang: Lang): string {
  const d = Math.max(0, Math.floor(Date.now() / 1000 - ts));
  if (d < 60) return lang === 'ar' ? 'الآن' : 'now';
  if (d < 3600) return lang === 'ar' ? `منذ ${Math.floor(d / 60)} د` : `${Math.floor(d / 60)}m`;
  if (d < 86400) return lang === 'ar' ? `منذ ${Math.floor(d / 3600)} س` : `${Math.floor(d / 3600)}h`;
  return lang === 'ar' ? `منذ ${Math.floor(d / 86400)} ي` : `${Math.floor(d / 86400)}d`;
}
