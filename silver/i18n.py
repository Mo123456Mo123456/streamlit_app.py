def rel_time(ts: float, now: float, lang: str) -> str:
    delta = max(0, int(now - ts))
    if delta < 60:
        return t("just_now", lang)
    if delta < 3600:
        return t("min_ago", lang, n=delta // 60)
    if delta < 86400:
        return t("hr_ago", lang, n=delta // 3600)
    return t("day_ago", lang, n=delta // 86400)
